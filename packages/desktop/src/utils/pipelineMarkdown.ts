/**
 * Markdown 流水线的起步骨架。
 *
 * 流水线是一份人工说明的流程文档：标题即步骤，执行交给编排 Agent。
 * 这里只给最小可跑的样例，人按需改写，不需要理解任何代码。
 */
export function markdownTemplate(name: string): string {
  return `---
name: ${name}
---

# 目标

一句话说明这条流水线要把什么变成什么。

# 流程

## 1. 建沙箱

建立隔离 worktree，就绪后报告分支、目录与端口。

## 2. Agent 编码

起一个 Agent 会话，任务需求：{{task.title}}，详细说明：{{task.description}}。
要求代码极简，改完确保基础编译通过。

## 3. 构建校验

在沙箱内执行 \`pnpm build\`。失败就停，把报错原文记为失败原因。

## 4. 人工验收

提交人工卡点，清单写清验收标准。驳回就把意见作为失败原因。

## 5. 合并与收尾

合并特性分支到本地开发分支，然后清理沙箱。
`;
}
